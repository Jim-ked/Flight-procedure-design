"""Read-only audit of frozen inputs; write audit artifacts only in Round4."""
from pathlib import Path
import json,csv,hashlib,re,sys
from datetime import datetime,timezone
sys.stdout.reconfigure(encoding='utf-8')
ROOT=Path(__file__).resolve().parents[2];O=ROOT/'recovered/round4';A=ROOT/'recovered/A6-Template';E=A/'evidence'
def sha(p):
 h=hashlib.sha256()
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1048576),b''):h.update(b)
 return h.hexdigest()
def rows(p):
 with p.open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
errors=[];frozen=json.loads((O/'frozen-inputs.json').read_text(encoding='utf-8'))
for m in frozen:
 p=ROOT/m['path']
 if not p.exists():errors.append('frozen missing '+m['path'])
 elif p.stat().st_size!=m['size'] or sha(p)!=m['sha256']:errors.append('frozen changed '+m['path'])
known={m['path'] for m in frozen};added=[]
for tree in [ROOT/'recovered',ROOT/'WsTools-master']:
 for p in tree.rglob('*'):
  if not p.is_file() or A in p.parents or O in p.parents:continue
  if str(p.relative_to(ROOT)) not in known:added.append(str(p.relative_to(ROOT)))
if added:errors+=['unexpected addition outside Round4 '+s for s in added]
material=rows(O/'material-baseline.csv')
for m in material:
 p=Path(m['Path'])
 if not p.exists() or sha(p)!=m['SHA256']:errors.append('material changed '+str(p))
methods=rows(E/'methods.csv');bytoken={m['processed_token']:m for m in methods}
body=rows(E/'body-provenance.csv')
for m in body:
 if m['ProcessedStatus']!='no_body' and not (E/(m['Processed']+'.il.txt')).exists():errors.append('processed IL absent '+m['Processed'])
 if m['RawStatus']!='no_body' and not (E/'raw'/(m['Original']+'.il.txt')).exists():errors.append('raw IL absent '+m['Original'])
decls=rows(E/'method-declarations.csv')
for m in decls:
 if not m['tokens'] or ';' in m['tokens']:errors.append('ambiguous declaration '+str(m))
comments=0
for p in A.glob('*.Recovered.cs'):
 for old,rva,t in re.findall(r'Original MethodDef: (0x[0-9A-F]+); Original RVA: (0x[0-9A-F]+); Processed MethodDef: (0x[0-9A-F]+)',p.read_text(encoding='utf-8')):
  comments+=1;m=bytoken.get(t)
  if not m or old!=m['original_token'] or rva!=m['original_rva']:errors.append('method comment mismatch '+p.name+' '+t)
fixtures=[]
for p in sorted((O/'fixtures').glob('*.json')):
 d=json.loads(p.read_text(encoding='utf-8'))
 if d=={} or d is None:errors.append('empty fixture '+p.name)
 fixtures.append(dict(path=str(p.relative_to(ROOT)),bytes=p.stat().st_size,sha256=sha(p)))
compiled=json.loads((O/'test-inputs.json').read_text(encoding='utf-8'))
for m in compiled:
 if sha(ROOT/m['path'])!=m['sha256']:errors.append('compiled input changed '+m['path'])
log=(O/'tests.log').read_text(encoding='utf-8');mt=re.search(r'PASS assertions=(\d+)',log)
if not mt or 'FAIL' in log:errors.append('no successful final tests')
required=['overview.md','event-map.md','turn-parameter-usage.md','holding.md','holding-xe-ye.md','base-turn.md','procedure-45-180.md','procedure-80-260.md','envelope.md','cad-output-map.md','cad-interactions.md','connections.md','shared-geometry.md','recovery-notes.md','standard-differences.md','callgraph.md','base-turn-control-points.csv','procedure-turn-angle-index.csv']
for name in required:
 if not (A/name).is_file():errors.append('missing deliverable '+name)
# Local markdown artifact links only, not code, Mermaid, external URLs or anchors.
for p in list(A.glob('*.md'))+[O/'closure.md']:
 for dest in re.findall(r'\]\(([^)]+)\)',p.read_text(encoding='utf-8')):
  target=p.parent/dest.split('#')[0]
  if target==O/'integrity-report.json':continue # generated by this audit after checks
  if '://' not in dest and not dest.startswith('#') and not target.exists():errors.append('broken link '+str(p.relative_to(ROOT))+' -> '+dest)
report=dict(timestamp=datetime.now(timezone.utc).isoformat(),status='PASS' if not errors else 'FAIL',frozen_files_checked=len(frozen),frozen_changed_or_missing=[e for e in errors if e.startswith('frozen')],unexpected_additions=added,material_files_checked=len(material),methoddefs=len(methods),writer_methoddefs=len(rows(E/'writers/methods.csv')),raw_stub_like=sum(m['RawStatus']=='stub_like' for m in body),processed_no_body=sum(m['ProcessedStatus']=='no_body' for m in body),method_comments_checked=comments,events=len(rows(E/'events.csv'))+len(rows(E/'shared-turn-events.csv')),fixtures=len(fixtures),assertions=int(mt[1]) if mt else None,compiled_inputs_checked=len(compiled),errors=errors,evidence_scope='static recovery and independent execution; no original DLL/AutoCAD execution')
(O/'integrity-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
# Manifest excludes itself and the audit report (which changes on each check).
out=[]
for tree in [A,O]:
 for p in sorted(tree.rglob('*')):
  if p.is_file() and p.name not in ['output-manifest.json','integrity-report.json']:out.append(dict(path=str(p.relative_to(ROOT)),size=p.stat().st_size,sha256=sha(p)))
(O/'output-manifest.json').write_text(json.dumps(out,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(report,ensure_ascii=False,indent=2));raise SystemExit(bool(errors))
